    Paragraph('2.2. Соответственно, общая продолжительность работы с Участником по Тарифам '
              '«Средний» и «Продвинутый» составляет 6 (шесть) недель: 3 недели основной части '
              'Программы в соответствии с пунктами 2.4 и 3.4 Оферты и 3 недели сопровождения '
              'внедрения после её завершения.', body),
    Paragraph('2.3. В период сопровождения внедрения Участнику Тарифов «Средний» '
              'и «Продвинутый» предоставляются: общий чат участников, техническая обратная связь '
              'и проверка практических результатов по заданиям Программы.', body),
