"""Дополнение №2 к публичной оферте: обновления материалов при бессрочном доступе.

Как и Дополнение №1, собирается отдельными страницами и дописывается к готовому
PDF через pypdf. Оригинальный договор не перенабирается: извлечение текста ломает
таблицу тарифов, а молча потерянный пункт стоит дороже любой вёрстки.

Запуск:
    python3 offer/addendum-2.build.py
Скрипт кладёт страницы дополнения во временный файл и дописывает их
к offer/public-offer.pdf.
"""
import sys
from pathlib import Path

from pypdf import PdfReader, PdfWriter
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib.units import mm
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer

FONTS = '/usr/share/fonts/truetype/dejavu/'
pdfmetrics.registerFont(TTFont('DJ', FONTS + 'DejaVuSans.ttf'))
pdfmetrics.registerFont(TTFont('DJ-B', FONTS + 'DejaVuSans-Bold.ttf'))

body = ParagraphStyle('body', fontName='DJ', fontSize=10, leading=15, spaceAfter=9)
h1 = ParagraphStyle('h1', fontName='DJ-B', fontSize=14, leading=19, spaceAfter=4, alignment=1)
sub = ParagraphStyle('sub', fontName='DJ', fontSize=10, leading=15, spaceAfter=18, alignment=1)
h2 = ParagraphStyle('h2', fontName='DJ-B', fontSize=11.5, leading=16, spaceBefore=12, spaceAfter=7)

OFFER = Path(__file__).resolve().parent / 'public-offer.pdf'
TMP = Path(__file__).resolve().parent / '.addendum-2.tmp.pdf'

doc = SimpleDocTemplate(
    str(TMP),
    pagesize=A4, leftMargin=20 * mm, rightMargin=20 * mm, topMargin=20 * mm, bottomMargin=18 * mm,
    title='Дополнение №2 к публичной оферте Seevasta',
)

story = [
    Paragraph('ДОПОЛНЕНИЕ № 2', h1),
    Paragraph('к Публичной оферте на оказание информационно-консультационных услуг<br/>'
              'в редакции от 3 октября 2026 года', sub),

    Paragraph('1. Общие положения', h2),
    Paragraph('1.1. Настоящее Дополнение является неотъемлемой частью Публичной оферты '
              'Индивидуального предпринимателя Севастьянова Матвея Алексеевича (ИНН 661305367793, '
              'ОГРНИП 325730000048020) на оказание информационно-консультационных услуг в редакции '
              'от 3 октября 2026 года (далее — Оферта).', body),
    Paragraph('1.2. Термины, определённые Офертой, используются в настоящем Дополнении '
              'в том же значении.', body),
    Paragraph('1.3. Настоящее Дополнение улучшает положение Заказчика и применяется ко всем '
              'Договорам, заключённым с даты его публикации.', body),

    Paragraph('2. Обновления Материалов при бессрочном доступе', h2),
    Paragraph('2.1. Участнику, которому доступ к записям модулей, записям групповых консультаций '
              'и Материалам предоставлен бессрочно в соответствии с абзацем вторым пункта 8.9 Оферты, '
              'вместе с таким доступом предоставляются обновления Материалов Программы, выпускаемые '
              'Исполнителем после завершения оказания услуг по Договору.', body),
    Paragraph('2.2. Под обновлениями в настоящем Дополнении понимаются изменения Материалов '
              'оплаченной Участником Программы, а именно: переснятые и дополненные записи занятий; '
              'актуализация содержания под изменения используемых сервисов; обновлённые шаблоны, '
              'промпты, инструкции и сопроводительные файлы, входящие в состав Программы.', body),
    Paragraph('2.3. Обновления предоставляются на той же образовательной платформе, в рамках того же '
              'доступа и без дополнительной оплаты, по мере их выпуска Исполнителем.', body),
    Paragraph('2.4. Срок предоставления обновлений совпадает со сроком доступа: обновления '
              'предоставляются, пока у Участника сохраняется бессрочный доступ по пункту 8.9 Оферты '
              'и пока работает образовательная платформа Seevasta.', body),

    Paragraph('3. Границы обязательства', h2),
    Paragraph('3.1. Обновлениями по настоящему Дополнению не являются и без дополнительной оплаты '
              'не предоставляются: новые самостоятельные программы, курсы и продукты Исполнителя; '
              'персональные консультации и сопровождение; участие в живых групповых консультациях '
              'последующих потоков.', body),
    Paragraph('3.2. Исполнитель не принимает на себя обязательство выпускать обновления '
              'с какой-либо периодичностью. Обязательство Исполнителя состоит в том, что выпущенные '
              'обновления Материалов предоставляются Участнику, указанному в пункте 2.1, '
              'без дополнительной оплаты.', body),
    Paragraph('3.3. Пункт 8.10 Оферты сохраняет силу: Исполнитель вправе разумно корректировать '
              'последовательность тем, конкретные демонстрационные сервисы и содержание отдельных '
              'практических примеров, если это не приводит к существенному уменьшению оплаченного '
              'объёма услуг.', body),
    Paragraph('3.4. Настоящее Дополнение не изменяет условия пункта 8.9 Оферты о том, кому и на какой '
              'срок предоставляется доступ. Участник, оплативший Тариф позднее срока, указанного '
              'в абзаце втором пункта 8.9, получает доступ и обновления на период, предусмотренный '
              'абзацем третьим того же пункта.', body),

    Paragraph('4. Прочие условия', h2),
    Paragraph('4.1. Во всём остальном, что не изменено настоящим Дополнением, действуют положения Оферты.', body),
    Paragraph('4.2. Ничто в настоящем Дополнении не ограничивает обязательные права потребителя, '
              'предусмотренные законодательством Российской Федерации.', body),

    Spacer(1, 16),
    Paragraph('Индивидуальный предприниматель Севастьянов Матвей Алексеевич<br/>'
              'ИНН 661305367793 · ОГРНИП 325730000048020<br/>'
              'Email: msevastanov1307@gmail.com', body),
]

doc.build(story)

offer_pages = PdfReader(str(OFFER)).pages
if len(offer_pages) != 12:
    sys.exit(f'ожидали 12 страниц (оферта + Дополнение №1), в файле {len(offer_pages)} — проверьте, '
             'не добавлено ли дополнение повторно')

writer = PdfWriter()
for page in offer_pages:
    writer.add_page(page)
for page in PdfReader(str(TMP)).pages:
    writer.add_page(page)
with open(OFFER, 'wb') as out:
    writer.write(out)
TMP.unlink()

print(f'готово: {len(PdfReader(str(OFFER)).pages)} страниц в offer/public-offer.pdf')
